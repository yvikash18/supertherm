import { chromium } from 'playwright';
const b = await chromium.launch();
const O=(n)=>new URL('../screenshots/'+n,import.meta.url).pathname;
const ctx = await b.newContext({viewport:{width:1440,height:900}});
const p = await ctx.newPage();
await p.goto('http://localhost:4321/branches',{waitUntil:'networkidle',timeout:40000});
await p.evaluate(()=>document.querySelector('iframe')?.scrollIntoView({block:'center'}));
await p.waitForTimeout(4000);
const hasIframe = await p.$eval('iframe', el=>el.src.includes('google.com/maps')).catch(()=>false);
console.log('MAP_IFRAME:', hasIframe);
await p.screenshot({path:O('branches-map.png')});
await b.close();
