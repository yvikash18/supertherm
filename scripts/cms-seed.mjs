// Generates d1/seed.sql from the current values in src/data/site.ts.
//   npm run cms:seed
// The seed only fills sections that have no saved content yet (INSERT OR IGNORE),
// so it is safe to run again on a database that has been edited.
import { buildSync } from 'esbuild';
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const root = new URL('..', import.meta.url);
const load = async (rel) => {
  const out = buildSync({
    entryPoints: [fileURLToPath(new URL(rel, root))],
    bundle: true,
    format: 'esm',
    write: false,
  });
  return import('data:text/javascript;base64,' + Buffer.from(out.outputFiles[0].text).toString('base64'));
};

const site = await load('src/data/site.ts');
const { SECTIONS } = await load('src/data/cms-sections.ts');

const q = (s) => `'${String(s).replace(/'/g, "''")}'`;
const at = '2000-01-01T00:00:00.000Z'; // fixed, so re-generating does not create a diff

const rows = SECTIONS.map((s) => {
  const content = {};
  for (const k of s.keys) {
    if (!(k in site)) throw new Error(`site.ts has no export "${k}" (listed in cms-sections.ts)`);
    content[k] = site[k];
  }
  return `-- ${s.label}\nINSERT OR IGNORE INTO pages (slug, content, updated_at, updated_by) VALUES (${q(s.slug)}, ${q(
    JSON.stringify(content)
  )}, ${q(at)}, 'seed');`;
});

// Guard: every content export of site.ts must belong to a section.
const covered = new Set(SECTIONS.flatMap((s) => s.keys));
const missing = Object.keys(site).filter((k) => !covered.has(k) && k !== 'certificates');
if (missing.length) throw new Error(`Not editable yet, add to cms-sections.ts: ${missing.join(', ')}`);

const sql = `-- GENERATED by scripts/cms-seed.mjs from src/data/site.ts. Do not edit by hand.
-- Fills the console with the site's built-in content. Existing rows are left alone.
--   npx wrangler d1 execute supertherm-cms --remote --file=d1/seed.sql   (or --local)

${rows.join('\n\n')}
`;
writeFileSync(new URL('d1/seed.sql', root), sql);
console.log(`Wrote d1/seed.sql (${SECTIONS.length} sections, ${sql.length} bytes)`);
